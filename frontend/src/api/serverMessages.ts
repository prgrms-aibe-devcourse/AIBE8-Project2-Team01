// 원인을 특정할 수 없을 때 쓰는 상태 코드별 중립 안내
// 화면에서는 보통 "○○하지 못했어요." 다음 줄에 붙는다
export function neutralByStatus(status: number): string | null {
  if (status === 400) return '입력한 내용을 다시 확인해 주세요.';
  if (status === 403) return '이 작업을 할 권한이 없어요.';
  if (status === 404) return '대상을 찾을 수 없어요.\n삭제되었거나 볼 수 없는 항목일 수 있어요.';
  if (status === 409) return '지금 상태에서는 처리할 수 없어요.\n화면을 새로 고친 뒤 다시 확인해 주세요.';
  if (status === 413) return '파일이 너무 커요.\n5MB 이하로 올려 주세요.';
  return null;
}
